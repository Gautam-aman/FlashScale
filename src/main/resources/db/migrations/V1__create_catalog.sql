
CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          sku VARCHAR(64) NOT NULL UNIQUE,
                          name VARCHAR(200) NOT NULL,
                          price_paise BIGINT NOT NULL
                              CHECK (price_paise >= 0)
);

CREATE TABLE flash_sales (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             title VARCHAR(160) NOT NULL,
                             starts_at TIMESTAMPTZ NOT NULL,
                             ends_at TIMESTAMPTZ NOT NULL,

                             CONSTRAINT valid_sale_period
                                 CHECK (ends_at > starts_at)
);

CREATE TABLE flash_sale_items (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  flash_sale_id BIGINT NOT NULL
                                      REFERENCES flash_sales(id),

                                  product_id BIGINT NOT NULL
                                      REFERENCES products(id),

                                  sale_price_paise BIGINT NOT NULL
                                      CHECK (sale_price_paise >= 0),

                                  total_stock INTEGER NOT NULL
                                      CHECK (total_stock >= 0),

                                  available_stock INTEGER NOT NULL
                                      CHECK (available_stock >= 0),

                                  CONSTRAINT valid_stock
                                      CHECK (available_stock <= total_stock),

                                  CONSTRAINT unique_sale_product
                                      UNIQUE (flash_sale_id, product_id)
);

CREATE INDEX idx_flash_sale_items_sale
    ON flash_sale_items(flash_sale_id);
